"""
27_paper_tables.py
==================
Writes every table in the paper as LaTeX, straight from the result files.

    python scripts/27_paper_tables.py     ->  paper/tables/*.tex

WHY THIS EXISTS
    A number typed into a .tex file by hand will eventually disagree with the
    data, and nobody will notice until a reviewer does. Every table the paper
    prints is generated here, from the same CSVs that `23_build_tables.py`
    reads, so the paper and `docs/COMPLETE_RESULTS.md` cannot drift apart.
    Re-run it whenever a result file changes; never edit paper/tables/*.tex.

OUTPUT (all booktabs, IEEEtran-safe)
    tab_dataset.tex     the splits
    tab_models.tex      model inventory: family, trainable parameters, constraint
    tab_endpoints.tex   quantum minus matched twin at both endpoints, with p
    tab_testauc.tex     test AUC, every model at every training size
    tab_attacks.tex     test AUC per attack type at full data
    tab_followup.tex    geometric difference, and quantum features in tree models
"""

import importlib
import os

import numpy as np
import pandas as pd
from scipy.stats import wilcoxon

sw = importlib.import_module("16_sweep")

OUT = "paper/tables"
NS = [571, 1429, 2857, 14286, 68296]
TWIN = {"Q_pre": "MLP_pre", "Q_reup": "MLP_reup", "Q_frozen": "MLP_frozen"}
ATT = ["speed_lie", "jump", "gap", "dark", "drift"]
ATT_LAB = {"speed_lie": "Speed falsif.", "jump": "Position jump", "gap": "Reporting gap",
           "dark": "Transponder off", "drift": "Gradual drift"}
NAME = {
    "Q_reup": "HQNN, data re-uploading", "Q_pre": "HQNN, classical pre-layer",
    "Q_frozen": "HQNN, frozen circuit (control)", "QSVM": "Quantum SVM",
    "gbt": "Gradient boosting", "rf": "Random forest", "logreg": "Logistic regression",
    "mlp": "MLP (12-5-1, 71 par.)", "MLP_reup": "Twin of re-uploading HQNN",
    "MLP_pre": "Twin of pre-layer HQNN", "MLP_frozen": "Twin of frozen HQNN",
    "iforest": "Isolation forest (no labels)", "rule": "Threshold rule (no labels)",
}
ORDER = ["Q_reup", "Q_pre", "Q_frozen", "QSVM", "gbt", "rf", "logreg", "mlp",
         "MLP_reup", "MLP_pre", "MLP_frozen", "iforest", "rule"]


def table(name, caption, label, header, rows, align, note=None, star=False):
    """One booktabs table. star=True spans both columns (table*)."""
    env = "table*" if star else "table"
    L = [f"% GENERATED by scripts/27_paper_tables.py -- do not edit by hand",
         f"\\begin{{{env}}}[t]", "\\centering",
         # single-column tables get a smaller face and tighter columns so they fit
         # the 3.5-inch IEEE column; full-width tables keep the normal size
         *([] if star else ["\\footnotesize", "\\setlength{\\tabcolsep}{4pt}"]),
         f"\\caption{{{caption}}}", f"\\label{{{label}}}",
         f"\\begin{{tabular}}{{{align}}}", "\\toprule", header + " \\\\", "\\midrule"]
    L += [r + " \\\\" for r in rows]
    L += ["\\bottomrule", "\\end{tabular}"]
    if note:
        L.append(f"\\\\[2pt]\\footnotesize {note}")
    L.append(f"\\end{{{env}}}")
    open(f"{OUT}/{name}", "w", encoding="utf-8").write("\n".join(L) + "\n")
    print("  wrote", name)


def main():
    os.makedirs(OUT, exist_ok=True)
    fs = pd.read_csv("results/full_sweep_results.csv")
    fin = pd.read_csv("results/final_results.csv")
    qs = pd.read_csv("results/qsvm_results.csv")
    qf = pd.read_csv("results/qfeat_results.csv")
    gd = pd.read_csv("results/geometric_difference.csv")

    # ------------------------------------------------------------- 1. dataset
    rows = []
    for split, f in (("Train", "train"), ("Validation", "val"), ("Test", "test")):
        d = pd.read_csv(f"data/dataset_{f}.csv")
        col = "MMSI" if "MMSI" in d.columns else "mmsi"
        rows.append(f"{split} & {len(d):,} & {d[col].nunique():,} & {int(d.label.sum()):,} & "
                    f"{d.label.mean()*100:.2f}\\%")
    table("tab_dataset.tex",
          "The dataset. Splits are vessel-disjoint: no MMSI appears in more than one split.",
          "tab:dataset", "Split & Windows & Vessels & Anomalous & Rate", rows, "lrrrr")

    # -------------------------------------------------------------- 2. models
    QS = ("Q_reup", "Q_pre", "Q_frozen")
    qp = {q: sw.q_params(sw.QARCH[q]) for q in QS}   # q_params takes the architecture dict
    cp = sw.CPARAMS
    # short labels: the full names push this table past the 3.5-inch column
    SHORT = {"Q_reup": "re-uploading", "Q_pre": "pre-layer", "Q_frozen": "frozen"}
    rows = [f"HQNN, {SHORT[q]} & {qp[q]} & {cp[sw.TWIN[q]]} & matched twin" for q in QS]
    rows += [f"Twin of {SHORT[q]} & {cp[sw.TWIN[q]]} & --- & matched" for q in QS]
    rows += ["Quantum SVM & 0 (kernel) & --- & none",
             "Gradient boosting & --- & --- & none",
             "Random forest & --- & --- & none",
             "Logistic regression & 13 & --- & none",
             "MLP (12-5-1) & 71 & --- & none",
             "Isolation forest & --- & --- & no labels",
             "Threshold rule & 0 & --- & no labels"]
    table("tab_models.tex",
          "Model inventory. $T$ counts trainable parameters. Every hybrid quantum network is "
          "matched to a classical twin of equal depth whose parameter count is never lower.",
          "tab:models", "Model & $T$ & Twin $T$ & Constraint", rows, "lrrl")

    # ----------------------------------------------------------- 3. endpoints
    rows = []
    for q, c in TWIN.items():
        cells = []
        for n in (571, 68296):
            a = fin[(fin.model == q) & (fin.N == n)].sort_values("seed").test_auc.values
            b = fin[(fin.model == c) & (fin.N == n)].sort_values("seed").test_auc.values
            p = wilcoxon(a, b).pvalue
            mark = "$^{*}$" if p < 0.05 else ""
            cells += [f"${a.mean()-b.mean():+.4f}${mark}", f"{p:.3f}"]
        rows.append(f"{NAME[q].split(', ')[1]} & " + " & ".join(cells))
    table("tab_endpoints.tex",
          "Quantum minus its matched classical twin on the test set, at the two endpoints. "
          "Ten paired seeds, Wilcoxon signed-rank.",
          "tab:endpoints",
          "Pair & $\\Delta$ $N{=}571$ & $p$ & $\\Delta$ $N{=}68{,}296$ & $p$",
          rows, "lrrrr", note="$^{*}$ $p<0.05$.")

    # ------------------------------------------------------------ 4. test AUC
    m = fs.groupby(["model", "N"]).test_auc.mean()
    best = {n: max(m[(k, n)] for k in ORDER if (k, n) in m.index) for n in NS}
    rows = []
    for k in ORDER:
        cells = []
        for n in NS:
            if (k, n) not in m.index:
                cells.append("---")
                continue
            v = m[(k, n)]
            cells.append(f"\\textbf{{{v:.4f}}}" if abs(v - best[n]) < 5e-5 else f"{v:.4f}")
        rows.append(f"{NAME[k]} & " + " & ".join(cells))
    table("tab_testauc.tex",
          "Test AUC for every model at every training-set size. Five seeds per cell, identical "
          "training windows across models. Bold marks the best model at that size. The quantum "
          "kernel has validation scores only and is reported separately.",
          "tab:testauc", "Model & " + " & ".join(f"$N{{=}}{n:,}$".replace(",", "{,}") for n in NS),
          rows, "l" + "r" * len(NS), star=True)

    # ------------------------------------------------------------- 5. attacks
    fm = [k for k in ORDER if k != "QSVM"]
    ba = {a: max(m0 for m0 in (fs[(fs.model == k) & (fs.N == 68296)][f"test_auc_{a}"].mean()
                               for k in fm) if not np.isnan(m0)) for a in ATT}
    rows = []
    for k in fm:
        cells = []
        for a in ATT:
            v = fs[(fs.model == k) & (fs.N == 68296)][f"test_auc_{a}"].mean()
            cells.append(f"\\textbf{{{v:.3f}}}" if abs(v - ba[a]) < 5e-4 else f"{v:.3f}")
        rows.append(f"{NAME[k]} & " + " & ".join(cells))
    table("tab_attacks.tex",
          "Test AUC by attack type at full training data. Bold marks the best model for that "
          "attack. Gradual drift, the largest attack class, is unsolved by every model.",
          "tab:attacks", "Model & " + " & ".join(ATT_LAB[a] for a in ATT),
          rows, "l" + "r" * len(ATT), star=True)

    # ------------------------------------------------------------ 6. followup
    rows = []
    for n in (571, 1429):
        t = gd[(gd.N == n) & (gd.lam == 0.001) & gd.fits]
        g = t.groupby("seed").g_gen.min()
        rows.append(f"Geometric difference, $N{{=}}{n:,}$".replace(",", "{,}") +
                    f" & ${g.median():.2f}$ & ${np.sqrt(n):.1f}$ & "
                    f"{g.median()/np.sqrt(n)*100:.0f}\\%")
    table("tab_geometric.tex",
          "Geometric difference between the quantum kernel and the best classical kernel that "
          "can fit the data, against the largest value it could take. A classical kernel can "
          "learn any function the quantum kernel can, at no more than $g^{2}$ times the model "
          "complexity.",
          "tab:geometric", "Quantity & $g$ & $\\sqrt{N}$ & Share of maximum", rows, "lrrr")

    rows = []
    for model in ("rf", "gbt"):
        for n in (571, 68296):
            a = qf[(qf.model == model) & (qf.arm == "+Q") & (qf.N == n)].sort_values("seed")
            cells = []
            for arm in ("base", "+RFF"):
                b = qf[(qf.model == model) & (qf.arm == arm) & (qf.N == n)].sort_values("seed")
                p = wilcoxon(a.test_auc, b.test_auc).pvalue
                cells.append(f"${a.test_auc.values.mean()-b.test_auc.values.mean():+.4f}$"
                             + ("$^{*}$" if p < 0.05 else ""))
            lab = "Random forest" if model == "rf" else "Gradient boosting"
            rows.append(f"{lab}, $N{{=}}{n:,}$".replace(",", "{,}") + " & " + " & ".join(cells))
    table("tab_qfeatures.tex",
          "Quantum features added to the two strongest classical models, against the plain model "
          "and against classical random features of the same count. Negative means the quantum "
          "features made the model worse. Ten paired seeds, test set.",
          "tab:qfeatures", "Model and size & vs.\\ plain & vs.\\ random features", rows, "lrr",
          note="$^{*}$ $p<0.05$, Wilcoxon signed-rank.")

    print(f"\nwrote 6 tables to {OUT}/ -- never edit these by hand, re-run this script")


if __name__ == "__main__":
    main()
